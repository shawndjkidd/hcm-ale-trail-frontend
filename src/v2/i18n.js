const V = { en, vn, kr, jp };

export function useV(language) {
  return V[language] || en;
}

export function fmt(str, vars = {}) {
  return String(str ?? '').replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export const WEEKDAY_LOCALE = { en: 'en-GB', vn: 'vi-VN', kr: 'ko-KR', jp: 'ja-JP' };

export function weekdayName(i, language) {
  // i: 0 = Sunday
  const base = new Date(Date.UTC(2024, 0, 7 + i)); // 7 Jan 2024 was a Sunday
  return base.toLocaleDateString(WEEKDAY_LOCALE[language] || 'en-GB', { weekday: 'short', timeZone: 'UTC' });
}

export function shortDate(iso, language) {
  if (!iso) return '';
  return new Date(iso).toLocaleDateString(WEEKDAY_LOCALE[language] || 'en-GB', {
    day: 'numeric', month: 'short', timeZone: 'Asia/Ho_Chi_Minh',
  });
}

export function monthName(language) {
  return new Date().toLocaleDateString(WEEKDAY_LOCALE[language] || 'en-GB', { month: 'long', timeZone: 'Asia/Ho_Chi_Minh' });
}
