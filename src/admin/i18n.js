import { useSyncExternalStore } from 'react';

// English / Vietnamese for the venue dashboard. Keys are the English wording, so anything
// not translated yet simply shows in English. The choice is remembered per browser.

const KEY = 'hcm-admin-lang';
let lang = (() => { try { return localStorage.getItem(KEY) === 'vi' ? 'vi' : 'en'; } catch { return 'en'; } })();
const subs = new Set();

export function setAdminLang(next) {
  lang = next === 'vi' ? 'vi' : 'en';
  try { localStorage.setItem(KEY, lang); } catch {}
  subs.forEach((f) => f());
}
export function useAdminLang() {
  return useSyncExternalStore((f) => { subs.add(f); return () => subs.delete(f); }, () => lang, () => 'en');
}

/** t('Some English', { n: 3 }) → translated text with {n} filled in. */
export function useT() {
  const current = useAdminLang();
  return (text, vars) => fill(current === 'vi' ? (VI[text] ?? text) : text, vars);
}
export function tr(text, vars) { return fill(lang === 'vi' ? (VI[text] ?? text) : text, vars); }
function fill(s, vars) {
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

